// Builds the game's UI into app/dist:
//   index.html   the shell, with every .story file inlined
//   story.js     the story engine, the clue ledger and the story UI (plain scripts)
//   ui.js        shared primitives (icons, motion, tooltip, dialogs) as window.SN; loaded first
//   bench.js     the workbench: editor, waveform, debugger (ES modules, bundled)
//   app.css      fonts, shared tokens, story styles, workbench styles
//   datasheet.html, fonts/
//
//   node ui/build.mjs            build once
//   node ui/build.mjs --watch    rebuild on change
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(here, '..');
const repo = path.resolve(app, '..');
const dist = path.join(app, 'dist');
const src = p => path.join(here, 'src', p);
const read = p => fs.readFileSync(p, 'utf8');

function storyFiles() {
  const dir = path.join(repo, 'content', 'story');
  return fs.readdirSync(dir).filter(f => f.endsWith('.story')).sort().map(name => ({ name, text: read(path.join(dir, name)) }));
}

const FONTS = [
  ['literata', 'Literata', [[400, 'normal'], [400, 'italic'], [600, 'normal']]],
  ['ibm-plex-mono', 'IBM Plex Mono', [[400, 'normal'], [500, 'normal']]],
  ['geist-sans', 'Geist', [[400, 'normal'], [500, 'normal'], [600, 'normal']]],
  ['architects-daughter', 'Architects Daughter', [[400, 'normal']]],
];

function fonts() {
  fs.mkdirSync(path.join(dist, 'fonts'), { recursive: true });
  let css = '';
  for (const [pkg, family, variants] of FONTS) {
    for (const [w, style] of variants) {
      for (const subset of ['latin', 'latin-ext']) {
        const file = `${pkg}-${subset}-${w}-${style}.woff2`;
        const from = path.join(app, 'node_modules', '@fontsource', pkg, 'files', file);
        if (!fs.existsSync(from)) continue;
        fs.copyFileSync(from, path.join(dist, 'fonts', file));
        const range = subset === 'latin'
          ? 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD'
          : 'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF';
        css += `@font-face{font-family:'${family}';font-style:${style};font-weight:${w};font-display:swap;src:url(fonts/${file}) format('woff2');unicode-range:${range};}\n`;
      }
    }
  }
  return css;
}

async function build() {
  const t0 = Date.now();
  fs.mkdirSync(dist, { recursive: true });
  // Story: engine + ledger (UMD) and the UI in one IIFE.
  const ui = ['ui-core.js', 'ui-stream.js', 'ui-panel.js', 'ui-app.js'].map(f => read(src('story/' + f))).join('\n');
  const story = read(src('story/engine.js')) + '\n' + read(src('story/ledger.js')) + "\n(function () {\n'use strict';\n" + ui + '\n})();\n';
  fs.writeFileSync(path.join(dist, 'story.js'), story);
  fs.copyFileSync(src('api.js'), path.join(dist, 'api.js'));
  // Shared primitives, then the workbench bundle.
  const common = {
    bundle: true,
    format: 'iife',
    target: 'es2020',
    minify: !process.argv.includes('--dev'),
    sourcemap: process.argv.includes('--dev') ? 'inline' : false,
    logLevel: 'warning',
  };
  await esbuild.build(Object.assign({ entryPoints: [src('shared/index.js')], outfile: path.join(dist, 'ui.js') }, common));
  await esbuild.build({
    entryPoints: [src('bench/main.js')],
    bundle: true,
    format: 'iife',
    target: 'es2020',
    minify: !process.argv.includes('--dev'),
    sourcemap: process.argv.includes('--dev') ? 'inline' : false,
    outfile: path.join(dist, 'bench.js'),
    loader: { '.html': 'text' },
    logLevel: 'warning',
  });
  // Styles.
  const css = fonts() + read(src('shared/tokens.css')) + '\n' + read(src('story/style.css')) + '\n' + read(src('bench/bench.css'));
  fs.writeFileSync(path.join(dist, 'app.css'), css);
  // Datasheet (generated by `k28 datasheet`).
  const ds = path.join(repo, 'content', 'sdk', 'datasheet.html');
  if (fs.existsSync(ds)) fs.copyFileSync(ds, path.join(dist, 'datasheet.html'));
  // The SDK files the game ships: content/sdk is the source of truth.
  const res = path.join(app, 'src-tauri', 'resources', 'sdk');
  fs.mkdirSync(res, { recursive: true });
  for (const f of ['startup.S', 'link.ld']) fs.copyFileSync(path.join(repo, 'content', 'sdk', f), path.join(res, f));
  // Shell with the story inlined.
  const tags = storyFiles().map(f => {
    if (/<\/script/i.test(f.text)) throw new Error(f.name + ' contains "</script"');
    return '<script type="text/plain" class="story-file" data-name="' + f.name + '">\n' + f.text + '</script>';
  }).join('\n');
  const html = read(src('shell.html')).replace('<!--STORY-->', () => tags);
  fs.writeFileSync(path.join(dist, 'index.html'), html);
  console.log(`built ${path.relative(repo, dist)} in ${Date.now() - t0} ms`);
}

await build();
if (process.argv.includes('--watch')) {
  let timer = null;
  const again = () => { clearTimeout(timer); timer = setTimeout(() => build().catch(e => console.error(e.message)), 100); };
  fs.watch(path.join(here, 'src'), { recursive: true }, again);
  fs.watch(path.join(repo, 'content'), { recursive: true }, again);
  console.log('watching…');
}
